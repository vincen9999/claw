def east(run):
    run.font.name = 'Microsoft YaHei'
    run._element.rPr.rFonts.set(qn('w:eastAsia'), 'Microsoft YaHei')

def title(t, sub=None):
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(t); r.bold=True; r.font.size=Pt(18); east(r)
    if sub:
        p2 = doc.add_paragraph(); p2.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r2 = p2.add_run(sub); r2.font.size=Pt(11); r2.font.color.rgb=RGBColor(0x55,0x55,0x55); east(r2)

def h1(t):
    p = doc.add_heading(level=1)
    r = p.add_run(t); east(r); r.font.color.rgb=RGBColor(0x1F,0x4E,0x79); r.bold=True

def h2(t):
    p = doc.add_heading(level=2)
    r = p.add_run(t); east(r); r.font.color.rgb=RGBColor(0x2E,0x74,0xB5); r.bold=True

def para(t, bold=False, size=10.5, color=None):
    p = doc.add_paragraph(); r = p.add_run(t); east(r); r.bold=bold; r.font.size=Pt(size)
    if color: r.font.color.rgb=RGBColor(*color)
    return p

def qline(num, text, ans):
    disp = {'√':'对', '×':'错'}.get(ans, ans)   # 判断题正文显示 对/错，速查表仍用 √/×
    p = doc.add_paragraph()
    r = p.add_run(f'{num}. {text}'); east(r); r.font.size=Pt(10.5)
    ra = p.add_run(f'　【答案：{disp}】'); east(ra); ra.bold=True; ra.font.size=Pt(10.5)
    ra.font.color.rgb = RGBColor(0xC0,0x00,0x00)
    return p

def qline_opt(num, text, options, ans):
    # 只保留正确答案对应的那一项，剔除错误选项
    correct = ''
    for part in re.split(r'[　;；]', options):
        part = part.strip()
        m = re.match(r'^([A-Da-d])\.\s*(.*)$', part)
        if m and m.group(1).upper() == ans.upper():
            correct = m.group(2).strip()
            break
    p = doc.add_paragraph()
    filled = re.sub(r'（[ 　]*）', '（' + correct + '）', text, count=1)
    r = p.add_run(f'{num}. {filled}'); east(r); r.font.size=Pt(10.5)
    ra = p.add_run(f'　【答案：{ans}. {correct}】'); east(ra); ra.bold=True; ra.font.size=Pt(10.5)
    ra.font.color.rgb = RGBColor(0xC0,0x00,0x00)
    return p

def quick_ref(title_text, ans_list, per_row=10):
    h2(title_text)
    for i in range(0, len(ans_list), per_row):
        chunk = ans_list[i:i+per_row]
        units = [f'{i+j+1}.{a}' for j,a in enumerate(chunk)]
        p = doc.add_paragraph(); r = p.add_run('　'.join(units)); east(r); r.font.size=Pt(10.5)

