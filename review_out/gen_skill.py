# -*- coding: utf-8 -*-
import re
from docx import Document
from docx.shared import Pt, RGBColor, Cm
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn

doc = Document()
normal = doc.styles['Normal']
normal.font.name = 'Microsoft YaHei'
normal._element.rPr.rFonts.set(qn('w:eastAsia'), 'Microsoft YaHei')
normal.font.size = Pt(10.5)

def east(run):
    run.font.name = 'Microsoft YaHei'
    run._element.rPr.rFonts.set(qn('w:eastAsia'), 'Microsoft YaHei')

def title(t, sub=None):
    p=doc.add_paragraph(); p.alignment=WD_ALIGN_PARAGRAPH.CENTER
    r=p.add_run(t); r.bold=True; r.font.size=Pt(18); east(r)
    if sub:
        p2=doc.add_paragraph(); p2.alignment=WD_ALIGN_PARAGRAPH.CENTER
        r2=p2.add_run(sub); r2.font.size=Pt(11); r2.font.color.rgb=RGBColor(0x55,0x55,0x55); east(r2)

def h1(t):
    p=doc.add_heading(level=1); r=p.add_run(t); east(r); r.font.color.rgb=RGBColor(0x1F,0x4E,0x79); r.bold=True

def h2(t):
    p=doc.add_heading(level=2); r=p.add_run(t); east(r); r.font.color.rgb=RGBColor(0x2E,0x74,0xB5); r.bold=True

def label(t):
    p=doc.add_paragraph(); r=p.add_run(t); east(r); r.bold=True; r.font.size=Pt(10.5); r.font.color.rgb=RGBColor(0xB0,0x3A,0x2E)
    return p

def para(t, size=10.5, color=None, indent=False):
    p=doc.add_paragraph()
    if indent: p.paragraph_format.left_indent=Cm(0.5)
    r=p.add_run(t); east(r); r.font.size=Pt(size)
    if color: r.font.color.rgb=RGBColor(*color)
    return p

def answer(t, bold_ans=True):
    p=doc.add_paragraph()
    r=p.add_run(t); east(r); r.font.size=Pt(10.5)
    return p

def module(title_text, bg, q_label, questions, answers):
    h2(title_text)
    label('【背景资料】'); para(bg, indent=True)
    label('【'+q_label+'】')
    # 将答案按起始序号归并成与题目一一对应的块：以 N. 开头视为新答案，否则为续行
    blocks, cur = [], None
    for a in answers:
        s = a.strip()
        if re.match(r'^\d+\.', s):
            cur = [a]; blocks.append(cur)
        else:
            if cur is None:
                cur = [a]; blocks.append(cur)
            else:
                cur.append(a)
    for i, q in enumerate(questions):
        para(q, indent=True)
        if i < len(blocks):
            p = doc.add_paragraph(); p.paragraph_format.left_indent=Cm(0.5)
            r = p.add_run('【参考答案】'); east(r); r.bold=True; r.font.size=Pt(10.5); r.font.color.rgb=RGBColor(0xB0,0x3A,0x2E)
            for line in blocks[i]:
                pp = doc.add_paragraph(); pp.paragraph_format.left_indent=Cm(0.9)
                rr = pp.add_run(line); east(rr); rr.font.size=Pt(10.5)

