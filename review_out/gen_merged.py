def set_eastasia(run):
    run.font.name = 'Microsoft YaHei'
    r = run._element.rPr.rFonts
    r.set(qn('w:eastAsia'), 'Microsoft YaHei')

def add_title(text, sub=None):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(text); r.bold = True; r.font.size = Pt(18); set_eastasia(r)
    if sub:
        p2 = doc.add_paragraph(); p2.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r2 = p2.add_run(sub); r2.font.size = Pt(11); r2.font.color.rgb = RGBColor(0x55,0x55,0x55); set_eastasia(r2)

def add_h1(text, color=(0x1F,0x4E,0x79)):
    p = doc.add_heading(level=1)
    r = p.add_run(text); set_eastasia(r); r.font.color.rgb = RGBColor(*color); r.bold=True
    return p

def add_h2(text, color=(0x2E,0x74,0xB5)):
    p = doc.add_heading(level=2)
    r = p.add_run(text); set_eastasia(r); r.font.color.rgb = RGBColor(*color); r.bold=True
    return p

def add_p(text, bold=False, size=10.5, color=None, indent=False):
    p = doc.add_paragraph()
    if indent: p.paragraph_format.left_indent = Cm(0.6)
    r = p.add_run(text); set_eastasia(r); r.bold = bold; r.font.size = Pt(size)
    if color: r.font.color.rgb = RGBColor(*color)
    return p

def add_bullet(text, bold_lead=None):
    p = doc.add_paragraph(style='List Bullet')
    if bold_lead:
        r = p.add_run(bold_lead); r.bold=True; set_eastasia(r)
        r2 = p.add_run(text); set_eastasia(r2)
    else:
        r = p.add_run(text); set_eastasia(r)
    return p

def shade(cell, hexcolor):
    tcPr = cell._tc.get_or_add_tcPr()
    sh = OxmlElement('w:shd'); sh.set(qn('w:val'),'clear'); sh.set(qn('w:color'),'auto'); sh.set(qn('w:fill'),hexcolor)
    tcPr.append(sh)

def add_table(headers, rows, widths=None, header_fill='1F4E79', font=9.5):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = 'Table Grid'; t.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr = t.rows[0].cells
    for i,h in enumerate(headers):
        hdr[i].text=''
        rr = hdr[i].paragraphs[0].add_run(h); rr.bold=True; set_eastasia(rr)
        rr.font.color.rgb = RGBColor(0xFF,0xFF,0xFF); rr.font.size=Pt(font)
        shade(hdr[i], header_fill)
    for row in rows:
        cells = t.add_row().cells
        for i,val in enumerate(row):
            cells[i].text=''
            rr = cells[i].paragraphs[0].add_run(val); set_eastasia(rr); rr.font.size=Pt(font)
    if widths:
        for i,w in enumerate(widths):
            for row in t.rows:
                row.cells[i].width = Cm(w)
    return t

def add_mnemonic(label, text):
    p = doc.add_paragraph()
    p.paragraph_format.left_indent = Cm(0.6)
    r = p.add_run(label+' '); r.bold=True; r.font.color.rgb=RGBColor(0xB0,0x3A,0x2E); set_eastasia(r)
    r2 = p.add_run(text); set_eastasia(r2); r2.font.size=Pt(10.5)
    return p

