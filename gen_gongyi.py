def set_cn(run, name='宋体', size=None, bold=None, color=None):
    run.font.name = name
    run._element.rPr.rFonts.set(qn('w:eastAsia'), name)
    if size is not None:
        run.font.size = Pt(size)
    if bold is not None:
        run.font.bold = bold
    if color is not None:
        run.font.color.rgb = color


def H(text, level=1):
    h = doc.add_heading('', level=level)
    run = h.add_run(text)
    set_cn(run, '黑体', {1: 15, 2: 13, 3: 12}.get(level, 12), True, RGBColor(0x1F, 0x3A, 0x5F))
    return h


def P(text, bold=False, indent=True, size=12, name='宋体'):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(4)
    if indent:
        p.paragraph_format.first_line_indent = Pt(24)
    run = p.add_run(text)
    set_cn(run, name, size, bold)
    return p


def BULLET(text):
    p = doc.add_paragraph(style='List Bullet')
    run = p.add_run(text)
    set_cn(run, '宋体', 12)
    return p


def table(headers, rows, font_size=10.5):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr = t.rows[0].cells
    for i, htext in enumerate(headers):
        hdr[i].text = ''
        run = hdr[i].paragraphs[0].add_run(htext)
        set_cn(run, '黑体', font_size, True)
        hdr[i].paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = ''
            run = cells[i].paragraphs[0].add_run(str(val))
            set_cn(run, '宋体', font_size)
    return t


